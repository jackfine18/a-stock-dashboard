def lookup(code):
    """
    根据6位行业代码返回 (一级名称, 二级名称, 三级名称)
    支持三层回退: 精确匹配 → 4位代码匹配 → 2位代码匹配
    """
    code = str(code).strip()
    if not code or len(code) < 2:
        return ("", "", "")

    prefix2 = code[:2]
    prefix4 = code[:4] if len(code) >= 4 else code

    # L1: 从2位前缀确定
    l1 = L1_MAP.get(prefix2, "")

    # L3: 精确匹配
    if code in L3_MAP:
        parent_prefix, l3 = L3_MAP[code]
        # L2: 从L2_MAP查4位代码
        l2_info = L2_MAP.get(prefix4)
        if l2_info:
            l2 = l2_info[1]
        else:
            # 回退: 取4位代码对应的L2, 如无则空
            l2 = ""
        return (l1 or L1_MAP.get(parent_prefix, ""), l2, l3)

    # L2: 4位代码匹配
    l2_info = L2_MAP.get(prefix4)
    if l2_info:
        l2 = l2_info[1]
    else:
        l2 = ""

    return (l1, l2, "")


